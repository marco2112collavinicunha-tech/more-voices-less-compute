"""Accuracy numbers, tables and figures for the report (called by s09_report_assets).

Sources (all generated by the pipeline):
  results/s01/<corpus>_counts.json      speakers, recordings
  results/s08b/torgo_matched.json       systems paired on identical recordings
  results/s08/<corpus>_summary.json     layer sweep (all draws), Speech Commands
  results/s03d/torgo_costs.json         costs in the TORGO scenario
"""
from __future__ import annotations
import pandas as pd

import json
from pathlib import Path
import os

import numpy as np

GROUPS = (("dysarthric", "Dys"), ("control", "Ctl"))
# system key -> (macro tag, label)
SYSTEMS = [
    ("shared_L12_logreg", "Shared", "Shared classifier, layer 12"),
    ("xpl_shared_own_L12_logreg", "SharedOwn", "Shared + own recordings, layer 12 (exploratory)"),
    ("frozen_L12_1nn", "Frozen", "Own recordings, nearest neighbour, layer 12"),
    ("frozen_L24_1nn", "FrozenTwentyfour", "Own recordings, nearest neighbour, layer 24"),
    ("shared_L24_logreg", "SharedTwentyfour", "Shared classifier, layer 24"),
    ("whisper_forced", "WhisperForced", "Whisper-medium, forced choice"),
    ("whisper_free", "WhisperFree", "Whisper-medium, free transcription"),
    ("finetune_full_ep10", "FtFullTen", "Retrain all layers, 10 epochs"),
    ("finetune_full_ep30", "FtFullThirty", "Retrain all layers, 30 epochs"),
    ("finetune_top4_ep10", "FtTopTen", "Retrain top 4 layers, 10 epochs"),
    ("finetune_top4_ep30", "FtTopThirty", "Retrain top 4 layers, 30 epochs"),
    ("finetune_lora_ep10", "FtLoraTen", "LoRA, 10 epochs"),
    ("finetune_lora_ep30", "FtLoraThirty", "LoRA, 30 epochs"),
    ("finetune_full_L12_ep10", "FtLtwelveTen", "Retrain layer-12 model, 10 epochs"),
    ("finetune_full_L12_ep30", "FtLtwelveThirty", "Retrain layer-12 model, 30 epochs"),
]
COST_KEY = {  # per recognition, per new user (keys of results/s03d)
    "shared_L12_logreg": ("L12", "shared_L12"), "xpl_shared_own_L12_logreg": ("L12", "xpl_shared_own_L12"),
    "frozen_L12_1nn": ("L12", "frozen_L12"), "frozen_L24_1nn": ("L24", "frozen_L24"), "shared_L24_logreg": ("L24", "shared_L12"),
    "whisper_forced": ("whisper_forced", None), "whisper_free": ("whisper_free", None),
    "finetune_full_ep10": ("L24", "finetune_full_ep10"), "finetune_full_ep30": ("L24", "finetune_full_ep30"),
    "finetune_top4_ep10": ("L24", "finetune_top4_ep10"), "finetune_lora_ep10": ("L24", "finetune_lora_ep10"),
    "finetune_top4_ep30": ("L24", "finetune_top4_ep30"), "finetune_lora_ep30": ("L24", "finetune_lora_ep30"),
    "finetune_full_L12_ep10": ("L12", "finetune_full_L12_ep10"), "finetune_full_L12_ep30": ("L12", "finetune_full_L12_ep30"),
}


def run(put, FIG, plt, BLUE, GREY, INK, INK2):
    _DK = os.environ.get("FIG_DARK") == "1"
    _WM = os.environ.get("FIG_WARM") == "1"
    GRID_C = "#2A2E36" if _DK else ("#E3DCCF" if _WM else "#e6e5e0")
    RUST = "#E9B44C" if _DK else ("#B5472B" if _WM else "#8c2f1e")
    BGC = "#0F1115" if _DK else (os.environ.get("FIG_BG", "#F6F1E7") if _WM else "white")
    out = {}
    c = json.load(open("results/s01/torgo_counts.json"))
    M = json.load(open("results/s08b/torgo_matched.json"))
    C = json.load(open("results/s03d/torgo_costs.json"))
    S8 = json.load(open("results/s08/torgo_summary.json"))
    sc = json.load(open("results/s08/speech_commands_summary.json")) if os.path.exists("results/s08/speech_commands_summary.json") else None
    scc = json.load(open("results/s01/speech_commands_counts.json")) if os.path.exists("results/s01/speech_commands_counts.json") else None

    # ------------------------------------------------------------ counts
    inc = c["speakers_included"]
    ps = c["per_speaker"]
    spk = {s["speaker"]: s for s in M["speakers"]}
    put("NSpkTorgo", len(inc), "{:d}")
    put("NSpkTorgoExcl", len(c["speakers_excluded"]), "{:d}")
    put("PrimaryKTorgo", c["primary_k"], "{}")
    put("NRecTorgoIncl", sum(ps[s]["n_recordings"] for s in inc), "{:,d}")
    put("NRecTorgoAll", c["n_recordings"], "{:,d}")
    for grp, tag in GROUPS:
        ss = [s for s in inc if ps[s]["group"] == grp]
        put(f"NSpkTorgo{tag}", len(ss), "{:d}")
        it = [spk[s]["n_items"] for s in ss]
        put(f"Items{tag}Min", min(it), "{:d}"); put(f"Items{tag}Max", max(it), "{:d}")
        put(f"Chance{tag}", 100 * float(np.mean([1 / i for i in it])), "{:.1f}")
        put(f"NTest{tag}", sum(spk[s]["n_test"] for s in ss), "{:,d}")
        put(f"NOther{tag}Min", min(spk[s]["n_other_train"] for s in ss), "{:,d}")
        put(f"NOther{tag}Max", max(spk[s]["n_other_train"] for s in ss), "{:,d}")
    put("NUsedTorgo", sum(spk[s]["n_train"] + spk[s]["n_test"] for s in spk), "{:,d}")
    put("ReproChecks", M["n_reproduction_checks"], "{:d}")
    put("ReproExact", M["n_reproduction_checks"] - len(M["reproduction_mismatches"]), "{:d}")

    # ------------------------------------------------------------ which Whisper analysis
    sysA = M["systems"].get("A_finetune_split", {})
    sysC = M["systems"].get("C_full_split_whisper", {})
    sysB = M["systems"].get("B_whisper_subset", {})
    whisper_src = {g: ("C" if sysC.get(g, {}).get("whisper_free", {}).get("n_speakers", 0) ==
                       len([s for s in inc if ps[s]["group"] == g]) else "B") for g, _ in GROUPS}
    sysW = {g: (sysC if whisper_src[g] == "C" else sysB).get(g, {}) for g, _ in GROUPS}
    import csv as _csv
    rb = [r for r in _csv.DictReader(open("results/s08b/torgo_matched_per_speaker.csv"))
          if r["analysis_group"] == "B_whisper_subset" and r["system"] == "whisper_free"]
    for g, gt in GROUPS:
        if whisper_src[g] == "C":
            put(f"WhisperSet{gt}", "every test recording", "{}")
        else:
            nb = np.mean([float(r["n_test"]) for r in rb if r["group"] == g])
            put(f"WhisperSet{gt}", f"the {nb:.0f} test recordings per speaker (on average) that a first, capped Whisper run had processed", "{}")
    put("WhisperSet", "every test recording" if all(v == "C" for v in whisper_src.values()) else
        "a subset of test recordings for some speakers (see each result)", "{}")
    # forced choice: the better of the two pre-registered scorings, per group (favours Whisper)
    forced = {}
    for grp, tag in GROUPS:
        a = sysW.get(grp, {})
        best = max(("whisper_forced_mean", "whisper_forced_sum"), key=lambda k: a.get(k, {}).get("mean_uar", -1))
        forced[grp] = best
    put("WhisperForcedScoring", "mean" if forced["dysarthric"] == "whisper_forced_mean" else "summed", "{}")

    def val(system, grp, src=None):
        if system == "whisper_forced":
            system = forced[grp]
        if system.startswith("whisper"):
            d = sysW[grp].get(system)
        else:
            d = sysA.get(grp, {}).get(system)
        return d

    table = []
    for key, tag, label in SYSTEMS:
        row = {"system": key, "label": label}
        for grp, gt in GROUPS:
            d = val(key, grp)
            put(f"Uar{gt}{tag}", None if d is None else 100 * d["mean_uar"])
            put(f"N{gt}{tag}", None if d is None else d["n_speakers"], "{:d}")
            if d is not None:
                put(f"Uar{gt}{tag}Lo", 100 * d["ci95"][0]); put(f"Uar{gt}{tag}Hi", 100 * d["ci95"][1])
            row[grp] = d
            rk, uk = COST_KEY[key]
            gm = C["group_means"][grp]
            row[f"rec_{grp}"] = gm["per_recognition_flops"][rk] / 1e9
            row[f"user_{grp}"] = (gm["per_user_flops"][uk] / 1e12) if uk else 0.0
        table.append(row)

    nchk = M.get("n_reproduction_checks", 0); mm = M.get("reproduction_mismatches", [])
    put("ReproChecks", nchk, "{:d}"); put("ReproExact", nchk - len(mm), "{:d}")
    put("ReproMaxDiff", max([100 * abs(r["s05"] - r["recomputed"]) for r in mm], default=0.0), "{:.1f}")
    # atypical-speech contrast (descriptive, across groups): points lost from controls to dysarthric speakers
    for key, tag in (("whisper_forced", "WhisperForced"), ("shared_L12_logreg", "Shared"), ("xpl_shared_own_L12_logreg", "SharedOwn")):
        dd_, cc_ = val(key, "dysarthric"), val(key, "control")
        put(f"Drop{tag}", None if (dd_ is None or cc_ is None) else 100 * (cc_["mean_uar"] - dd_["mean_uar"]), "{:.1f}")

    # ------------------------------------------------------------ paired results
    def pair(ag, grp, name):
        return M.get("paired_extra", {}).get(ag, {}).get(grp, {}).get(name) or \
            M.get("paired", {}).get(ag, {}).get(grp, {}).get(name)
    agWg = {g: ("C_full_split_whisper" if whisper_src[g] == "C" else "B_whisper_subset") for g, _ in GROUPS}
    specs = [
        ("HfourPrimary", "A_finetune_split", "frozen_L12_1nn - finetune_full_ep10"),
        ("FrozenVsFtLtwelve", "A_finetune_split", "frozen_L12_1nn - finetune_full_L12_ep10"),
        ("SharedVsFtLtwelve", "A_finetune_split", "shared_L12_logreg - finetune_full_L12_ep10"),
        ("SharedVsFrozen", "A_finetune_split", "shared_L12_logreg - frozen_L12_1nn"),
        ("OwnAdds", "A_finetune_split", "xpl_shared_own_L12_logreg - shared_L12_logreg"),
        ("LayerFrozen", "A_finetune_split", "frozen_L12_1nn - frozen_L24_1nn"),
        ("LayerShared", "A_finetune_split", "shared_L12_logreg - shared_L24_logreg"),
        ("SharedVsWhisperFree", None, "shared_L12_logreg - whisper_free"),
    ]
    LAB = {"HfourPrimary": ("own-recording nearest neighbour", "full retraining"),
           "FrozenVsFtLtwelve": ("own-recording nearest neighbour", "retraining the cut model"),
           "SharedVsFtLtwelve": ("the shared classifier", "retraining the cut model"),
           "SharedVsFrozen": ("the shared classifier", "own-recording nearest neighbour"),
           "OwnAdds": ("shared + own", "shared alone"),
           "LayerFrozen": ("layer 12", "layer 24"), "LayerShared": ("layer 12", "layer 24"),
           "SharedVsWhisperFree": ("the shared classifier", "Whisper's free transcription"),
           "SharedVsWhisperForced": ("the shared classifier", "Whisper's forced choice"),
           "SharedOwnVsWhisperForced": ("shared + own", "Whisper's forced choice")}

    def reading(r, a, b):
        if r is None:
            return None
        if "ci_90_low" not in r:
            return f"no test (only {r.get('n', 0)} speakers)"
        lo, hi, m = r["ci_90_low"], r["ci_90_high"], M["margin_points"]
        if lo > -m and hi < m:
            return f"equivalent within {m:g} points"
        if lo > m:
            return f"{a} better by more than {m:g} points"
        if hi < -m:
            return f"{b} better by more than {m:g} points"
        if lo > -m:
            return f"{a} not worse by more than {m:g} points (non-inferior); equivalence not shown"
        if hi < m:
            return f"{a} not better by more than {m:g} points; equivalence not shown"
        return "inconclusive"
    for grp, gt in GROUPS:
        sp_ = specs + [("SharedVsWhisperForced", None, f"shared_L12_logreg - {forced[grp]}"),
                       ("SharedOwnVsWhisperForced", None, f"xpl_shared_own_L12_logreg - {forced[grp]}")]
        for tag, ag, name in sp_:
            r = pair(ag or agWg[grp], grp, name)
            ok = r is not None and "mean_diff" in r
            put(f"{tag}{gt}Diff", r["mean_diff"] if ok else None, "{:+.1f}")
            put(f"{tag}{gt}Lo", r["ci_90_low"] if ok else None, "{:+.1f}")
            put(f"{tag}{gt}Hi", r["ci_90_high"] if ok else None, "{:+.1f}")
            put(f"{tag}{gt}N", (r or {}).get("n"), "{:d}")
            put(f"{tag}{gt}Better", (r or {}).get("n_better"), "{:d}")
            dd = list(((r or {}).get("per_speaker_diff_points") or {}).values())
            put(f"{tag}{gt}Tied", sum(abs(x) < 0.05 for x in dd) if dd else None, "{:d}")
            put(f"{tag}{gt}Worse", sum(x <= -0.05 for x in dd) if dd else None, "{:d}")
            put(f"{tag}{gt}MinDiff", min(dd) if dd else None, "{:+.0f}")
            put(f"{tag}{gt}MaxDiff", max(dd) if dd else None, "{:+.0f}")
            put(f"{tag}{gt}Reading", reading(r, *LAB[tag]), "{}")
            out[f"{tag}{gt}"] = r

    for grp, gt in GROUPS:
        s8 = S8["systems"].get(grp, {})
        for key, tag in (("shared_L18_logreg", "SharedLeighteen"), ("frozen_L12_int8_1nn", "IntEightFive"),
                         ("frozen_L12_1nn", "FrozenFive"), ("frozen_L18_1nn", "FrozenLeighteenFive")):
            put(f"Uar{gt}{tag}", 100 * s8[key]["mean_uar"] if key in s8 else None)
        sp_g = [v for v in C["speakers"].values() if v["group"] == grp]
        st = [int(np.ceil(v["n_train"] / 8)) * 10 for v in sp_g]
        put(f"Steps{gt}Min", min(st), "{:d}"); put(f"Steps{gt}Max", max(st), "{:d}")
        put(f"NTrain{gt}Min", min(v["n_train"] for v in sp_g), "{:d}"); put(f"NTrain{gt}Max", max(v["n_train"] for v in sp_g), "{:d}")


    # retraining runs that predicted a single word (UAR exactly 1/K)
    import pandas as _pd2
    s7 = _pd2.read_csv("results/s07/torgo_finetune.csv").drop_duplicates(subset=["speaker", "k", "draw", "system", "epoch"], keep="last")
    s7 = s7[s7.system.isin(["finetune_full", "finetune_top4", "finetune_lora"])]
    nit = {s_: spk[s_]["n_items"] for s_ in spk}
    single = sum(abs(r.uar - 1 / nit[r.speaker]) < 1e-3 for r in s7.itertuples())
    put("FtTopRuns", len(s7), "{:d}"); put("FtTopRunsSingle", int(single), "{:d}")

    # microphones: share of head-mounted recordings in each speaker's learning and test recordings (draw 0)
    from greenafi.data import load_config as _lc, make_split as _ms, read_manifest as _rm, by_speaker as _bs
    _cfg = _lc(); _p = _cfg["personalisation"]
    _rows = [r for r in _rm("data/manifests/torgo.csv") if r["speaker"] in set(inc)]
    _path = {r["utt_id"]: r["path"] for r in _rows}
    mic = {}
    for s_, rs_ in _bs(_rows).items():
        sp_ = _ms(rs_, s_, 1, 0, _cfg["seed"], _p["min_test_per_item"], _p["min_items_per_speaker"])
        hh = lambda ids: 100 * sum("headMic" in _path[u] for u in ids) / len(ids)
        mic[s_] = (hh(sp_.train), hh(sp_.test))
    same_mic = sorted(s_ for s_, (a_, b_) in mic.items() if a_ == 100 and b_ == 100)
    put("NSameMic", len(same_mic), "{:d}")
    put("SameMicList", ", ".join(same_mic), "{}")
    import csv as _csv2
    _ps = list(_csv2.DictReader(open("results/s08b/torgo_matched_per_speaker.csv")))
    def _m(system, ag, ss):
        v = [float(r["uar"]) for r in _ps if r["system"] == system and r["analysis_group"] == ag and r["speaker"] in ss]
        return 100 * float(np.mean(v)) if len(v) == len(ss) and v else None
    agC = "C_full_split_whisper"
    for tag, sysn, ag in (("Shared", "shared_L12_logreg", "A_finetune_split"), ("Own", "frozen_L12_1nn", "A_finetune_split"),
                          ("WhisperForced", "whisper_forced_mean", agC)):
        put(f"SameMic{tag}", _m(sysn, ag, same_mic))
    # ------------------------------------------------------------ costs in the TORGO scenario
    for grp, gt in GROUPS:
        gm = C["group_means"][grp]
        r = gm["per_recognition_flops"]
        put(f"Sec{gt}", gm["mean_s_test"], "{:.1f}")
        put(f"GflopRec{gt}Ltwelve", r["L12"] / 1e9, "{:.0f}")
        put(f"GflopRec{gt}Ltwentyfour", r["L24"] / 1e9, "{:.0f}")
        put(f"GflopRec{gt}WhisperFree", r["whisper_free"] / 1e9, "{:,.0f}")
        put(f"GflopRec{gt}WhisperForced", r["whisper_forced"] / 1e9, "{:,.0f}")
        put(f"RatioRec{gt}WhisperFree", r["whisper_free"] / r["L12"], "{:.0f}")
        put(f"RatioRec{gt}WhisperForced", r["whisper_forced"] / r["L12"], "{:.0f}")
        u = gm["per_user_flops"]
        put(f"TflopUser{gt}Frozen", u["frozen_L12"] / 1e12, "{:.2f}")
        put(f"TflopUser{gt}FtFullTen", u["finetune_full_ep10"] / 1e12, "{:.0f}")
        put(f"TflopUser{gt}FtLtwelveTen", u["finetune_full_L12_ep10"] / 1e12, "{:.0f}")
        put(f"RatioUser{gt}FtFullTen", u["finetune_full_ep10"] / u["frozen_L12"], "{:.0f}")
        put(f"RatioUser{gt}FtLtwelveTen", u["finetune_full_L12_ep10"] / u["frozen_L12"], "{:.0f}")
        _sg = [v for v in C["speakers"].values() if v["group"] == grp]
        _rr = [v["per_recognition_flops"]["whisper_forced"] / v["per_recognition_flops"]["L12"] for v in _sg]
        put(f"RatioRec{gt}WhisperForcedMin", min(_rr), "{:.0f}"); put(f"RatioRec{gt}WhisperForcedMax", max(_rr), "{:.0f}")
        _ft = [v["per_user_flops"][m] / 1e12 for v in _sg for m in ("finetune_full_L12_ep10", "finetune_full_ep10")]
        put(f"TflopUser{gt}FtTenMin", min(_ft), "{:.0f}"); put(f"TflopUser{gt}FtTenMax", max(_ft), "{:.0f}")
    put("SecShareFit", C["shared_fit_seconds_largest"].get("seconds"), "{:.1f}")
    put("NShareFit", C["shared_fit_seconds_largest"].get("n_recordings"), "{:,d}")
    put("SaveLtwelveTorgo", 100 * (1 - C["group_means"]["dysarthric"]["per_recognition_flops"]["L12"] /
                                   C["group_means"]["dysarthric"]["per_recognition_flops"]["L24"]), "{:.0f}")


    # ------------------------------------------------------------ energy per recognition, in plain units
    J = json.load(open("results/s03c/energy.json"))["J_per_GFLOP"]["low_cost_arm_board"]
    gmD = C["group_means"]["dysarthric"]["per_recognition_flops"]
    jl12 = gmD["L12"] / 1e9 * J
    jwf = gmD["whisper_forced"] / 1e9 * J
    jwfree = gmD["whisper_free"] / 1e9 * J
    put("JRecLtwelve", jl12, "{:.1f}"); put("JRecWhisperForced", jwf, "{:,.0f}"); put("JRecWhisperFree", jwfree, "{:,.0f}")
    BATT_WH = 15.0  # a typical 4,000 mAh phone battery at 3.85 V
    put("BattWh", BATT_WH, "{:.0f}")
    put("RecPerBattLtwelve", BATT_WH * 3600 / jl12, "{:,.0f}")
    put("RecPerBattWhisper", BATT_WH * 3600 / jwf, "{:,.0f}")
    import csv as _c3
    LCr = {(r["system"], r["uses_per_day"]): r for r in _c3.DictReader(open("results/s03c/lifecycle.csv"))}
    wh12 = float(LCr[("Personalized, truncated at layer 12 (1-NN)", "100")]["user_year_Wh"])
    whw = float(LCr[("Generic: Whisper-medium, forced choice (12)", "100")]["user_year_Wh"])  # the comparator used throughout (forced choice); free transcription is 3,116 Wh
    put("PctBattDayWhisperFree", 100 * float(LCr[("Generic: Whisper-medium, free transcription", "100")]["user_year_Wh"]) / 365 / BATT_WH, "{:.0f}")
    put("ChargesYearLtwelve", wh12 / BATT_WH, "{:.0f}"); put("ChargesYearWhisper", whw / BATT_WH, "{:,.0f}")
    put("PctBattDayLtwelve", 100 * wh12 / 365 / BATT_WH, "{:.1f}"); put("PctBattDayWhisper", 100 * whw / 365 / BATT_WH, "{:.0f}")
    gr = json.load(open("config/grids.json")); allg = {**gr["founding_members"], **gr["other_members"]}
    hi_c, lo_c = max(allg, key=allg.get), min(allg, key=allg.get)
    put("GridHiName", hi_c, "{}"); put("GridLoName", lo_c, "{}")
    put("GridHi", allg[hi_c], "{:.0f}"); put("GridLo", allg[lo_c], "{:.0f}")
    put("GridSpread", allg[hi_c] / allg[lo_c], "{:.0f}")
    put("DesignGapYearFree", whw / wh12, "{:.0f}")
    # deployment scenario (2.2-s messages, 12 messages): per-recognition energy and the forced-choice year
    S_WF = "Generic: Whisper-medium, forced choice (12)"
    whf = float(LCr[(S_WF, "100")]["user_year_Wh"])
    jsl12 = float(LCr[("Personalized, truncated at layer 12 (1-NN)", "100")]["inference_J"])
    jswf = float(LCr[(S_WF, "100")]["inference_J"])
    put("JScenLtwelve", jsl12, "{:.0f}"); put("JScenWhisperForced", jswf, "{:,.0f}")
    put("RatioScenWhisperForced", jswf / jsl12, "{:.0f}")
    put("DesignGapYear", whf / wh12, "{:.0f}")
    put("TonnesHundredKBrazilWhisperForced", whf * 1e5 / 1000 * allg["Brazil"] / 1e6, "{:.0f}")
    put("MwhHundredKLtwelve", wh12 * 1e5 / 1e6, "{:.0f}"); put("MwhHundredKWhisperForced", whf * 1e5 / 1e6, "{:,.0f}")
    put("GcoLtwelveLo", wh12 / 1000 * allg[lo_c], "{:.0f}"); put("GcoLtwelveHi", wh12 / 1000 * allg[hi_c], "{:.0f}")
    put("TonnesHundredKBrazil", wh12 * 1e5 / 1000 * allg["Brazil"] / 1e6, "{:.1f}")
    put("TonnesHundredKIndia", wh12 * 1e5 / 1000 * allg["India"] / 1e6, "{:.1f}")
    # one-off cost of the shared pool (embedding other speakers' recordings once per vocabulary)
    for grp, gt in GROUPS:
        v = [x["shared_oneoff_embed_flops"] / 1e12 for x in C["speakers"].values() if x["group"] == grp]
